/**
 * Makes apps/console/src/map-data.ts: the world outline (without Antarctica) and Sri Lanka, as SVG
 * paths, with the projection numbers the console needs to place clients on them. The console then
 * needs no map library. Source: Natural Earth (public domain) via world-atlas.
 *
 * Only needed if the maps change. In an empty folder:
 *   npm i d3-geo@3.1.1 topojson-client@3.1.0 world-atlas@2.0.2
 * then, from the repository:
 *   node tools/console/make-map.mjs <that folder>
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const from = process.argv[2];
if (!from) throw new Error("usage: node tools/console/make-map.mjs <folder with d3-geo, topojson-client and world-atlas installed>");
const require = createRequire(join(resolve(from), "package.json"));
const { geoMercator, geoNaturalEarth1, geoPath } = require("d3-geo");
const { feature, merge } = require("topojson-client");

const round = (path) => path.replace(/(\d+\.\d+)/g, (n) => String(Math.round(Number(n) * 10) / 10));

// World: Natural Earth projection, 960 × 470.
const c110 = require("world-atlas/countries-110m.json");
const land = merge(c110, c110.objects.countries.geometries.filter((g) => g.properties.name !== "Antarctica"));
const W = 960;
const H = 470;
const world = geoNaturalEarth1().fitExtent([[4, 4], [W - 4, H - 4]], land);
const worldPath = round(geoPath(world)(land));

// Sri Lanka: Mercator, 220 × 320, from the finer 1:50m map.
const c50 = require("world-atlas/countries-50m.json");
const lk = feature(c50, c50.objects.countries.geometries.find((g) => g.properties.name === "Sri Lanka"));
const LW = 220;
const LH = 320;
const sl = geoMercator().fitExtent([[12, 12], [LW - 12, LH - 12]], lk);
const lkPath = round(geoPath(sl)(lk));

const out = `/* Generated by tools/console/make-map.mjs from Natural Earth (public domain) via world-atlas. Do not edit. */
/** Natural Earth projection of the world (without Antarctica). */
export const WORLD = { width: ${W}, height: ${H}, scale: ${world.scale()}, translate: [${world.translate().join(", ")}] as const, path: ${JSON.stringify(worldPath)} };
/** Mercator projection of Sri Lanka. */
export const SRI_LANKA = { width: ${LW}, height: ${LH}, scale: ${sl.scale()}, translate: [${sl.translate().join(", ")}] as const, path: ${JSON.stringify(lkPath)} };
`;
writeFileSync(join(root, "apps/console/src/map-data.ts"), out);
console.log(`apps/console/src/map-data.ts: world ${worldPath.length} characters, Sri Lanka ${lkPath.length}`);
